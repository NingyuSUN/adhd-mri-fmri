def nii_to_ants(nii_img):
    """
    Convert nibabel NIfTI -> ANTs image preserving spacing+origin+direction.
    Make sure origin/spacing/direction are Python lists (ANTsPy requirement).
    """
    data = nii_img.get_fdata().astype(np.float32)
    aff  = np.array(nii_img.affine, dtype=np.float64)

    # spacing (x,y,z)
    spacing = list(map(float, nii_img.header.get_zooms()[:3]))

    # origin must be list/tuple of length 3
    origin = list(map(float, aff[:3, 3].tolist()))

    # direction must be 3x3 (list of lists)
    direction = (aff[:3, :3] / np.array(spacing)[None, :]).astype(np.float64)
    direction = direction.tolist()

    return ants.from_numpy(
        data,
        spacing=spacing,
        origin=origin,
        direction=direction
    )


