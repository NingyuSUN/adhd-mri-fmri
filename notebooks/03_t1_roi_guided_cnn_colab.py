subj = subj.copy()
subj["y_hat"] = (subj["y_pred"] >= best_thr).astype(int)

subj["group"] = np.where((subj.y_true==1) & (subj.y_hat==1), "TP",
                 np.where((subj.y_true==0) & (subj.y_hat==0), "TN",
                 np.where((subj.y_true==0) & (subj.y_hat==1), "FP", "FN")))

subj["is_error"] = (subj["y_hat"] != subj["y_true"]).astype(int)

print("\nGroup counts:")
display(subj["group"].value_counts())


