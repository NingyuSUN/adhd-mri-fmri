SEARCH_DIR = "/content/drive/MyDrive"   # 你也可以改成更具体的目录，比如 /content/drive/MyDrive/ADHD200-data
CANDIDATES = sorted(
    glob.glob(os.path.join(SEARCH_DIR, "**", "*pred*.csv"), recursive=True)
)

print(f"Search dir: {SEARCH_DIR}")
print(f"Found {len(CANDIDATES)} candidate pred csv files (showing up to 30):")
for p in CANDIDATES[:30]:
    print(" -", p)

# ✅ 你可以在这里手动指定你要用的文件
PRED_PATH = None  # <-- 改成你的路径字符串，例如: "/content/drive/MyDrive/ADHD200-data/preds_subject_oof.csv"

if PRED_PATH is None:
    if len(CANDIDATES) == 0:
        raise FileNotFoundError(
            "No *pred*.csv found under SEARCH_DIR. "
            "Please set SEARCH_DIR to the folder you saved preds into, "
            "or manually set PRED_PATH."
        )
    # 默认用第一个（你也可以改成最后一个）
    PRED_PATH = CANDIDATES[0]
    print("\n[Auto-select] Using:", PRED_PATH)
else:
    print("\n[Manual] Using:", PRED_PATH)


# -------------------------
# 2) Load predictions
# -------------------------
df = pd.read_csv(PRED_PATH)
print("\nLoaded shape:", df.shape)
print("Columns:", list(df.columns))
display(df.head())


# -------------------------
# 3) Standardize columns
# -------------------------
# 你可能的列名：y_true/y, y_pred/p/p_oof, subject id: sub_id, site: site
# 我们做一个“智能映射”，把它统一成：sub_id, y_true, y_pred, site(可选)

def pick_first_existing(cols, candidates):
    for c in candidates:
        if c in cols:
            return c
    return None

cols = set(df.columns)

sub_col  = pick_first_existing(cols, ["sub_id", "subject", "subject_id", "SubID", "SUB_ID"])
y_col    = pick_first_existing(cols, ["y_true", "y", "label", "target"])
p_col    = pick_first_existing(cols, ["y_pred", "p", "p_oof", "prob", "pred", "pred_prob", "y_score"])
site_col = pick_first_existing(cols, ["site", "Site", "scanner_site", "dataset", "center"])

if sub_col is None or y_col is None or p_col is None:
    raise ValueError(
        f"Missing required columns.\n"
        f"Detected sub_id col: {sub_col}\n"
        f"Detected y col: {y_col}\n"
        f"Detected pred col: {p_col}\n"
        f"Please make sure your csv includes subject id + label + probability."
    )

work = df.copy()
work = work.rename(columns={sub_col:"sub_id", y_col:"y_true", p_col:"y_pred"})
if site_col is not None:
    work = work.rename(columns={site_col:"site"})
else:
    work["site"] = "NA"

# 确保类型正确
work["y_true"] = work["y_true"].astype(int)
work["y_pred"] = work["y_pred"].astype(float)

print("\nStandardized columns:", list(work.columns))
display(work[["sub_id","y_true","y_pred","site"]].head())


# -------------------------
# 4) If slice-level (duplicate sub_id), aggregate to subject-level
# -------------------------
dup = work["sub_id"].duplicated().any()
if dup:
    print("\nDetected duplicated sub_id -> assuming slice-level rows. Aggregating to subject-level by mean prob.")
    subj = (work
            .groupby(["sub_id","y_true","site"], as_index=False)["y_pred"]
            .mean())
else:
    subj = work[["sub_id","y_true","y_pred","site"]].copy()

print("\nSubject-level table shape:", subj.shape)
display(subj.head())


# -------------------------
# 5) Global metrics + best threshold (Youden J)
# -------------------------
y = subj["y_true"].values
p = subj["y_pred"].values

auc = roc_auc_score(y, p)
fpr, tpr, thr = roc_curve(y, p)
j = tpr - fpr
best_i = int(np.argmax(j))
best_thr = float(thr[best_i])

y_hat = (p >= best_thr).astype(int)
acc  = accuracy_score(y, y_hat)
bacc = balanced_accuracy_score(y, y_hat)
cm   = confusion_matrix(y, y_hat)

print("\n===== Global performance =====")
print(f"AUC: {auc:.4f}")
print(f"Best threshold (Youden J): {best_thr:.4f}")
print(f"Accuracy: {acc:.4f}")
print(f"Balanced Accuracy: {bacc:.4f}")
print("Confusion matrix [ [TN FP], [FN TP] ]:\n", cm)


# -------------------------
