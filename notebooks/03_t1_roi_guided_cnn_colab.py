def dx_text_to_y(dx_series):
    """
    Convert site participants.tsv 'dx' text to binary:
      TD -> 0
      ADHD-* -> 1
    Handles numeric-like too.
    """
    if dx_series is None:
        return None

    s = dx_series

    # numeric-like
    if pd.api.types.is_numeric_dtype(s):
        y = np.full(len(s), np.nan, dtype=float)
        y[pd.Series(s).isin([0])] = 0
        y[pd.Series(s).isin([1,2,3])] = 1
        return y

    ss = s.astype(str).str.strip().str.lower()

    y = np.full(len(ss), np.nan, dtype=float)

    # common ADHD200 participants.tsv wording
    y[ss.str.contains("typically developing")] = 0
    y[ss.str.contains("control")] = 0
    y[ss.str.fullmatch("td")] = 0

    y[ss.str.contains("adhd")] = 1

    # handle explicit numeric strings if present
    y[ss.isin(["0"])] = 0
    y[ss.isin(["1","2","3"])] = 1

    return y

