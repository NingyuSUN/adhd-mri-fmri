CONF_FP_THR = 0.80
CONF_FN_THR = 0.20

conf_fp = subj[(subj.y_true==0) & (subj.y_pred>=CONF_FP_THR)].sort_values("y_pred", ascending=False)
conf_fn = subj[(subj.y_true==1) & (subj.y_pred<=CONF_FN_THR)].sort_values("y_pred", ascending=True)

print("\n===== Confident wrong =====")
print("Confident FP (true=0, pred>=0.80):", len(conf_fp))
print("Confident FN (true=1, pred<=0.20):", len(conf_fn))

display(conf_fp.head(20))
display(conf_fn.head(20))


# -------------------------
# 9) Site-wise performance + error concentration
