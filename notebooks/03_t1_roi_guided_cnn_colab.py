def slice_cache_path(sub_id: str, z_list) -> str:
    z_sig = "-".join(map(str, z_list))
    return os.path.join(SLICE_CACHE_DIR, f"{sub_id}_roi_z{z_sig}.npz")

def load_warp_from_cache(sub_id: str):
    path = warp_cache_path(sub_id)
    if os.path.exists(path):
        return nib.load(path)
    return None

def load_or_build_subject_slices(sub_id: str, t1_path: str, z_list, roi_mask_3d: np.ndarray):
    """
    Cache-first:
      1) If slice cache exists -> load X (Z,H,W)
      2) Else load warped NIfTI from WARP cache -> cut ROI slices -> save slice cache
      3) If warp cache missing -> return None (skip subject)
    """
    spath = slice_cache_path(sub_id, z_list)
    if os.path.exists(spath):
        try:
            return np.load(spath)["X"].astype(np.float32)
        except Exception:
            pass  # fall through

    wimg = load_warp_from_cache(sub_id)
    if wimg is None:
        # Cache missing: skip
        return None

    vol = wimg.get_fdata().astype(np.float32)
    if vol.shape != roi_mask_3d.shape:
        # Sometimes cached warp might not match atlas grid; try resample to atlas
        try:
            vol_img = nib.Nifti1Image(vol, wimg.affine, wimg.header)
            vol_rs = image.resample_to_img(vol_img, atlas_img, interpolation="continuous")
            vol = vol_rs.get_fdata().astype(np.float32)
        except Exception:
            return None

    X_list = []
    for z in z_list:
        sl = vol[:, :, z]
        m  = roi_mask_3d[:, :, z]
        X_list.append(sl * m)

    X = np.stack(X_list, axis=0).astype(np.float32)
    np.savez_compressed(spath, X=X)
    return X

def build_roi_dataset_cached(df_sub: pd.DataFrame):
    """
    Build slice-level dataset from cached subject slices.
    Returns:
      X: (N_slices, H, W, 1)
      y: (N_slices,)
      sub_ids: (N_slices,)
      kept_subjects: number of subjects kept
      skipped_subjects: number skipped due to missing cache
    """
    X_list, y_list, sub_list = [], [], []
    kept, skipped = 0, 0

    for _, row in df_sub.iterrows():
        sub_id = row["sub_id"]
        t1_path = row["t1_path"]
        y = int(row["y"])

        X_sub = load_or_build_subject_slices(sub_id, t1_path, Z_SLICES, roi_mask)
        if X_sub is None:
            skipped += 1
            continue

        kept += 1
        for i in range(X_sub.shape[0]):
            X_list.append(X_sub[i])
            y_list.append(y)
            sub_list.append(sub_id)

    if kept == 0:
        raise RuntimeError("No subjects kept. Check WARP cache naming/path and atlas alignment.")

    X = np.stack(X_list, axis=0).astype(np.float32)[..., None]
    y = np.array(y_list, dtype=np.int32)
    sub_ids = np.array(sub_list)

    return X, y, sub_ids, kept, skipped

