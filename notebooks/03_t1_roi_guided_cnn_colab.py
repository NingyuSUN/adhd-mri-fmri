# ---------- 8) Registration with caching: subject T1 -> MNI 2mm (Rigid) ----------
def cache_path(sub_id):
    return os.path.join(CACHE_DIR, f"{sub_id}_mni2mm_float16.npy")

def get_warped_mni2mm(sub_id, t1_path, type_of_transform="Rigid"):
    """
    Returns a numpy volume aligned to MNI 2mm grid (same voxel grid as mni_2mm_nii),
    cached as float16.
    """
    p = cache_path(sub_id)
    if os.path.exists(p):
        return np.load(p).astype(np.float32)

    # load moving
    moving_nii = nib.load(t1_path)

    # speed/stability: resample moving to MNI 2mm grid before ANTs
    moving_2mm = image.resample_to_img(moving_nii, mni_2mm_nii, interpolation="continuous")

    # safest: write temp nifti, read via ants.image_read
    with tempfile.NamedTemporaryFile(suffix=".nii.gz", delete=False) as f:
        nib.save(moving_2mm, f.name)
        moving_ants = ants.image_read(f.name)
    os.remove(f.name)

    reg = ants.registration(
        fixed=fixed_ants,
        moving=moving_ants,
        type_of_transform=type_of_transform
    )

    vol = reg["warpedmovout"].numpy().astype(np.float32)
    np.save(p, vol.astype(np.float16))
    return vol

