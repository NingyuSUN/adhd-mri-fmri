# ---------- 5) Utils ----------
def resize_slice(sl2d, h=TARGET_H, w=TARGET_W):
    """sl2d: (H,W) float -> (h,w,1) float32"""
    sl = sl2d[..., np.newaxis].astype(np.float32)
    sl = tf.image.resize(sl, [h, w], method="bilinear").numpy().astype(np.float32)
    return sl

def normalize_slice(sl2d, eps=1e-6):
    """simple z-score normalization per slice"""
    m = np.nanmean(sl2d)
    s = np.nanstd(sl2d)
    if not np.isfinite(s) or s < eps:
        return (sl2d - m).astype(np.float32)
    return ((sl2d - m) / (s + eps)).astype(np.float32)

def bootstrap_auc_ci(y_true, y_score, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    y_true = np.asarray(y_true)
    y_score = np.asarray(y_score)
    N = len(y_true)
    aucs = []
    for _ in range(n):
        idx = rng.integers(0, N, N)
        if len(np.unique(y_true[idx])) < 2:
            continue
        aucs.append(roc_auc_score(y_true[idx], y_score[idx]))
    aucs = np.asarray(aucs)
    return float(np.mean(aucs)), float(np.quantile(aucs, 0.025)), float(np.quantile(aucs, 0.975))

