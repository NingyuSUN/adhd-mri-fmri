def hist_by_group(df, group, bins=30):
    vals = df.loc[df.group==group, "y_pred"].values
    plt.figure()
    plt.hist(vals, bins=bins)
    plt.title(f"Pred prob distribution: {group} (n={len(vals)})")
    plt.xlabel("y_pred")
    plt.ylabel("count")
    plt.show()

for g in ["TP","TN","FP","FN"]:
    hist_by_group(subj, g)


