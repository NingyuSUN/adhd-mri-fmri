# ---------- 11) Build ROI-guided slice dataset ----------
def build_roi_dataset(df_sub, roi_z):
    """
    Returns slice-level dataset:
      X: (N_slices, H, W, 1)
      y: (N_slices,)
      sub_ids: (N_slices,)  (for subject aggregation later)
    """
    X_list, y_list, sub_list = [], [], []

    for _, row in df_sub.iterrows():
        sub_id = row["sub_id"]
        t1_path = row["t1_path"]
        label = int(row["y"])

        # registration -> MNI 2mm
        vol = get_warped_mni2mm(sub_id, t1_path, type_of_transform="Rigid")  # (X,Y,Z) in MNI grid

        # extract ROI-selected slices
        for z in roi_z:
            if z < 0 or z >= vol.shape[2]:
                continue
            sl = vol[:, :, z]

            # normalize + resize
            sl = normalize_slice(sl)
            sl = resize_slice(sl, TARGET_H, TARGET_W)

            X_list.append(sl)
            y_list.append(label)
            sub_list.append(sub_id)

    X = np.stack(X_list, axis=0).astype(np.float32)
    y = np.array(y_list, dtype=np.int32)
    sub_ids = np.array(sub_list)
    return X, y, sub_ids

