def build_graph(ts, label):
    fc = conn.fit_transform([ts])[0]
    # 填充 NaN
    fc = np.nan_to_num(fc)
    x = torch.tensor(fc, dtype=torch.float)
    edge_index = []
    for i in range(fc.shape[0]):
        for j in range(fc.shape[0]):
            # We are creating a fully connected graph for now, so every node has an edge to every other node
            # The GNN will learn to weigh these edges
            if i != j:
                edge_index.append([i, j])
    # Handle case where there are no edges (e.g., if fc_matrix was 1x1 or all zeros after nan_to_num)
    # Though with 48 ROIs and correlation, this is unlikely.
    if not edge_index and fc.shape[0] > 0: # Ensure at least self-loops if no other edges, or handle tiny graph
        # For simplicity, if no edges, we can create an empty edge_index or skip the graph if it truly has no connections
        # Given fc.shape[0] is guaranteed to be target_roi_count, this won't be an empty graph
        pass # No need for self-loops for now, GCNConv handles this implicitly with bias or aggregation

    edge_index = torch.tensor(edge_index).t().contiguous()
    return Data(x=x, edge_index=edge_index, y=torch.tensor([label]))

