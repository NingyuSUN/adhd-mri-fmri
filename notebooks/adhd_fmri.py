def normalize_subject_id(x):
    x = str(x).strip()
    x = x.replace("_", "-")
    if not x.startswith("sub-"):
        x = f"sub-{x}"
    return x

def normalize_label(dx):
    if pd.isna(dx):
        return np.nan

    s = str(dx).strip().lower()

    # 映射逻辑：TDC 为 0，各种 ADHD 类型为 1
    mapping = {
        "0": 0,
        "1": 1,
        "2": 1,
        "3": 1,
        "control": 0,
        "tdc": 0,
        "typically developing children": 0,
        "healthy": 0,
        "adhd": 1,
        "adhd-combined": 1,
        "adhd-inattentive": 1,
        "adhd-hyperactive/impulsive": 1,
        "case": 1
    }

    if s in mapping:
        return mapping[s]

    try:
        v = float(s)
        if v == 0:
            return 0
        elif v in [1, 2, 3]:
            return 1
    except:
        pass

    return np.nan

