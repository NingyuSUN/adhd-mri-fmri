def load_k_slices(t1_path, k=K_SLICES, zmin=ZMIN, zmax=ZMAX):
    """
    从 3D T1 里取 k 张切片（默认取中间 30%~70%），每张做 min-max normalize + resize
    返回 list[(H,W,1)]，float32
    """
    vol = nib.load(t1_path).get_fdata()
    z = vol.shape[2]

    zs = np.linspace(z * zmin, z * zmax, k).astype(int)
    zs = np.clip(zs, 0, z - 1)

    out = []
    for zi in zs:
        sl = vol[:, :, zi].astype(np.float32)
        vmin, vmax = sl.min(), sl.max()
        if vmax > vmin:
            sl = (sl - vmin) / (vmax - vmin)
        else:
            sl = np.zeros_like(sl, dtype=np.float32)

        sl = resize_slice(sl)  # (TARGET_H, TARGET_W, 1)
        out.append(sl)

    return out

