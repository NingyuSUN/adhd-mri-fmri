def nib_to_ants(img_nii):
    """
    Convert nibabel NIfTI image -> ants image
    """
    data = img_nii.get_fdata().astype(np.float32)
    spacing = img_nii.header.get_zooms()[:3]
    return ants.from_numpy(data, spacing=spacing)

fixed_ants = nib_to_ants(mni_t1)

# 2) 定义 register_to_mni（Affine，课堂版）
def register_to_mni(moving_path, fixed_ants=fixed_ants):
    """
    moving_path: subject T1 NIfTI path
    return:
        warped_ants : subject T1 warped to MNI space (ants image)
        reg         : transform dictionary (for debug / extension)
    """
    moving_nii = nib.load(moving_path)
    moving_ants = nib_to_ants(moving_nii)

    reg = ants.registration(
        fixed=fixed_ants,
        moving=moving_ants,
        type_of_transform="Affine"   # Rigid + Affine，速度可接受
    )

    warped = reg["warpedmovout"]
    return warped, reg

