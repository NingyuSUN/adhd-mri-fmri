"""训练曲线（Cell 10.5）

train_AUC 在 0.45–0.55 之间随机波动

val_AUC 是一条直线 0.5

解读

训练集：模型在“试图”学一些弱模式

验证集：完全没有稳定的泛化信号

这说明不是过拟合，而是**信息不足**。
（如果是过拟合，train 会一路升、val 会一路掉。）
"""

# ===============================
# Cell 11 - Evaluate: AUC + CM + R90 threshold
# ===============================

from sklearn.metrics import roc_auc_score, confusion_matrix
import numpy as np

y_prob = model.predict(X_test).ravel()
test_auc = roc_auc_score(y_test, y_prob)
print("Test AUC:", test_auc)

def eval_at_threshold(y_true, y_prob, thr):
    y_pred = (y_prob >= thr).astype(int)
    cm = confusion_matrix(y_true, y_pred)
    tn, fp, fn, tp = cm.ravel()
    recall = tp / (tp + fn + 1e-9)
    precision = tp / (tp + fp + 1e-9)
    acc = (tp + tn) / (tp + tn + fp + fn + 1e-9)
    return {"thr": float(thr), "TN": int(tn), "FP": int(fp), "FN": int(fn), "TP": int(tp),
            "Recall": float(recall), "Precision": float(precision), "ACC": float(acc)}

print("\n== Threshold 0.5 ==")
print(eval_at_threshold(y_test, y_prob, 0.5))

# R90：找最小阈值使 Recall >= 0.90
thr_list = np.linspace(0, 1, 1001)
best = None
for thr in thr_list:
    r = eval_at_threshold(y_test, y_prob, thr)
    if r["Recall"] >= 0.90:
        best = r
        break

print("\n== R90 (Recall >= 0.90) ==")
print(best if best else "No threshold achieves Recall >= 0.90 on this test set.")

