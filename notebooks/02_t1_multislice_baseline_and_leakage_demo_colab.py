def select_topk_z(mask_nii, k=TARGET_K, min_pix=MIN_ROI_PIX, fallback=(0.25, 0.75)):
    m = mask_nii.get_fdata().astype(np.uint8)
    z = m.shape[2]
    counts = m.sum(axis=(0, 1))

    valid = np.where(counts >= min_pix)[0]
    if len(valid) < k:
        # 如果有效层太少：用中间区域补齐
        zmin, zmax = fallback
        extra = np.linspace(z*zmin, z*zmax, k).astype(int)
        extra = np.clip(extra, 0, z-1)
        # 合并去重，再按 counts 排序取前 k
        cand = np.unique(np.concatenate([valid, extra]))
        cand = cand[np.argsort(counts[cand])[::-1]]
        pick = np.sort(cand[:k])
        return pick, counts
    else:
        valid_sorted = valid[np.argsort(counts[valid])[::-1]]
        pick = np.sort(valid_sorted[:k])
        return pick, counts

